import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const root = process.cwd();
const sources = ['.env', '.env.local'];
const values = { ...loadEnvFiles(sources), ...process.env };
const required = [
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_DATABASE_URL',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID',
];

const missing = required.filter((key) => !values[key]?.trim());
if (missing.length) {
  console.error(`Missing required environment variables: ${missing.join(', ')}`);
  console.error('Copy .env.example to .env for local development or configure the values in CI.');
  process.exit(1);
}

const target = resolve(root, 'src/environments/environment.generated.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, renderConfig(values), 'utf8');

function loadEnvFiles(paths) {
  return paths.reduce((result, path) => {
    const fullPath = resolve(root, path);
    if (!existsSync(fullPath)) return result;
    return { ...result, ...parseEnv(readFileSync(fullPath, 'utf8')) };
  }, {});
}

function parseEnv(content) {
  return Object.fromEntries(
    content
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith('#') && line.includes('='))
      .map((line) => {
        const index = line.indexOf('=');
        return [line.slice(0, index).trim(), unquote(line.slice(index + 1).trim())];
      }),
  );
}

function unquote(value) {
  if (value.length < 2) return value;
  const quoted = (value.startsWith('"') && value.endsWith('"'))
    || (value.startsWith("'") && value.endsWith("'"));
  return quoted ? value.slice(1, -1) : value;
}

function renderConfig(env) {
  const config = {
    apiKey: env.FIREBASE_API_KEY,
    authDomain: env.FIREBASE_AUTH_DOMAIN,
    databaseURL: env.FIREBASE_DATABASE_URL,
    projectId: env.FIREBASE_PROJECT_ID,
    storageBucket: env.FIREBASE_STORAGE_BUCKET,
    messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID,
    appId: env.FIREBASE_APP_ID,
  };

  return `// Generated by scripts/generate-environment.mjs. Do not edit or commit.\n\nexport const firebaseConfig = ${JSON.stringify(config, null, 2)} as const;\n`;
}
